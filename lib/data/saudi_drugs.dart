import '../models/medication_info.dart';

class SaudiDrug {
  final String id;
  final String nameEn;
  final String nameAr;
  final String formKey; // tablet/capsule/ml/drops/spray/cream/injection/units
  final String strength;
  final String ingredient;
  final String usage; // دواعي الاستخدام (سطر موجز)
  final bool otc; // يُصرف بدون وصفة طبية

  const SaudiDrug({
    required this.id,
    required this.nameEn,
    required this.nameAr,
    required this.formKey,
    required this.strength,
    required this.ingredient,
    required this.usage,
    required this.otc,
  });

  MedicationInfo toInfo() => MedicationInfo(
    source: 'saudi',
    rxcui: 'saudi:$id',
    name: nameEn,
    synonym: nameAr,
    doseForm: formKey,
    strength: strength,
    tty: 'saudi',
    fetchedAt: DateTime.now().millisecondsSinceEpoch,
  );
}

/// Normalize Arabic text for matching: unify alef forms, taa marbuta/haa,
/// yaa/alif maqsura, and strip harakat.
String normalizeArabic(String input) => input
    .replaceAll(RegExp('[\\u064B-\\u065F\\u0670]'), '')
    .replaceAll('أ', 'ا')
    .replaceAll('إ', 'ا')
    .replaceAll('آ', 'ا')
    .replaceAll('ة', 'ه')
    .replaceAll('ى', 'ي')
    .trim()
    .toLowerCase();

